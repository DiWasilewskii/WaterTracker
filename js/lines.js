// ---------- Підстановки ----------

function fillLine(text, vars) {
    const female = gameState.gender === 'female';
    const v = Object.assign({
        n: gameState.userName || 'друже',
        goal: gameState.calculatedGoal,
        left: Math.max(0, gameState.calculatedGoal - gameState.waterDrunk),
        days: gameState.daysSurvived
    }, vars || {});
    return text
        .replace(/\{([^{}|]*)\|([^{}]*)\}/g, (m, a, b) => (female ? b : a))
        .replace(/\{(\w+)\}/g, (m, k) => (v[k] !== undefined ? v[k] : m));
}

// ---------- Без повторів протягом дня ----------

// Детермінований «перемішаний» порядок пулу на конкретний день
function seededOrder(seedText, len) {
    let h = 2166136261;
    for (let i = 0; i < seedText.length; i++) h = Math.imul(h ^ seedText.charCodeAt(i), 16777619);
    const order = Array.from({ length: len }, (_, i) => i);
    for (let i = len - 1; i > 0; i--) {
        h = Math.imul(h ^ (h >>> 15), 2246822507) ^ Math.imul(h ^ (h >>> 13), 3266489909);
        const j = (h >>> 0) % (i + 1);
        [order[i], order[j]] = [order[j], order[i]];
    }
    return order;
}

// Репліка на екрані: ще не показана сьогодні (коли пул вичерпано — починаємо коло знову)
function pickStatusLine(pool) {
    const today = dateKey(new Date());
    if (!gameState.linesUsed || gameState.linesUsed.day !== today) {
        gameState.linesUsed = { day: today, ids: [] };
    }
    const used = gameState.linesUsed.ids;
    const lines = LINES[pool];
    let free = lines.map((_, i) => i).filter(i => !used.includes(`${pool}:${i}`));
    if (!free.length) {
        gameState.linesUsed.ids = used.filter(id => !id.startsWith(pool + ':'));
        free = lines.map((_, i) => i);
    }
    const i = free[Math.floor(Math.random() * free.length)];
    gameState.linesUsed.ids.push(`${pool}:${i}`);
    return lines[i];
}

// Сповіщення: k-те з пулу за денним порядком (k — денний лічильник цього пулу)
function notifLineAt(pool, k) {
    const lines = NOTIF_LINES[pool];
    const order = seededOrder(`${dateKey(new Date())}:${pool}`, lines.length);
    return lines[order[k % lines.length]];
}

// Денні лічильники сповіщень (щоб не повторювались після кожного пиття)
function notifCounters() {
    const today = dateKey(new Date());
    if (!gameState.notifSeq || gameState.notifSeq.day !== today) {
        gameState.notifSeq = { day: today, c: {} };
    }
    return gameState.notifSeq.c;
}
